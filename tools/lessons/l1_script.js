const cell = (children, w, fill) => new TableCell({ children, width: { size: w, type: WidthType.DXA }, borders, shading: fill ? { type: ShadingType.CLEAR, color: 'auto', fill } : undefined, margins: { top: 70, bottom: 70, left: 100, right: 100 } });

// 台詞行：'🖱️' 開頭＝按一下（藍綠粗體）、'（' 開頭＝動作（灰）、其他＝老師說的話
function sayParas(lines) {
  return lines.map(l => {
    if (l.startsWith('🖱️')) return P([r(l, { bold: true, color: TEAL })], { after: 40 });
    if (l.startsWith('（')) return P([r(l, { color: SOFT, size: 20 })], { after: 40 });
    if (l.startsWith('⚠')) return P([r(l, { bold: true, color: RED, size: 20 })], { after: 40 });
    return P([r('「' + l + '」')], { after: 40 });
  });
}
const COLS = [1150, 5900, W - 1150 - 5900];
function rowOf(x) {
  return new TableRow({ cantSplit: true, children: [
    cell([P([r(x.p, { bold: true, size: 24 })], { after: 20 }), P([r(x.t, { size: 18, color: SOFT })])], COLS[0], 'F4EFE6'),
    cell(sayParas(x.say), COLS[1]),
    cell((x.stu || []).map(s => P([r(s, { size: 20 })], { after: 40 })), COLS[2], 'FBF8F2'),
  ] });
}
function segment(title, rows) {
  const head = new TableRow({ tableHeader: true, children: [
    cell([P([r('簡報頁', { bold: true, color: 'FFFFFF', size: 20 })])], COLS[0], INK),
    cell([P([r('老師說／老師做', { bold: true, color: 'FFFFFF', size: 20 })])], COLS[1], INK),
    cell([P([r('學生做什麼・小提醒', { bold: true, color: 'FFFFFF', size: 20 })])], COLS[2], INK)] });
  return [P([r(title, { size: 24, bold: true, color: RED })], { before: 200, after: 80, keepNext: true }),
          new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: COLS, layout: TableLayoutType.FIXED, rows: [head, ...rows.map(rowOf)] })];
}

