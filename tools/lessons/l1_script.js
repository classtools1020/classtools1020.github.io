const r = (t, o = {}) => new TextRun({ text: t, font: FONT, size: o.size || 22, bold: o.bold, color: o.color || INK });
const P = (runs, o = {}) => new Paragraph({ children: Array.isArray(runs) ? runs : [r(runs, o)], spacing: { before: o.before || 0, after: o.after ?? 60, line: o.line || 300 }, alignment: o.align, numbering: o.bullet ? { reference: 'b', level: 0 } : undefined, keepNext: o.keepNext });
